import digimonTypeCards from './digimonTypeCards';
import equipmentCards from './equipmentCards';
import energyCards from './energyCards';
import summonDigimonCards from './summonDigimonCards';

let autoGeneratedId = 0;

const withAutoGeneratedId = (cards) =>
  cards.map((card) => {
    autoGeneratedId += 1;
    card.autoGeneratedId = autoGeneratedId;
    return card;
  });

const digimons = withAutoGeneratedId([...digimonTypeCards].reverse());
const equipments = withAutoGeneratedId([...equipmentCards]);
const energies = withAutoGeneratedId([...energyCards]);
const summonDigimons = withAutoGeneratedId([...summonDigimonCards]);

export { digimons, equipments, energies, summonDigimons };
